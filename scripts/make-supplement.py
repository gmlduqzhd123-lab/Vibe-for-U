"""새 기능 수업 보충 안내(Word)를 만든다. PDF는 LibreOffice로 바꾼다.

사용: python3 scripts/make-supplement.py
      soffice --headless --convert-to pdf --outdir public/materials public/materials/new-features-guide.docx
"""
from docx import Document
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.oxml.ns import qn
from docx.shared import Pt, Cm, RGBColor

OUT = "public/materials/new-features-guide.docx"
FONT = "Malgun Gothic"

doc = Document()
for s in doc.sections:
    s.top_margin = s.bottom_margin = Cm(1.8)
    s.left_margin = s.right_margin = Cm(2)
for name in ("Normal", "Heading 1", "Heading 2", "Title"):
    st = doc.styles[name]
    st.font.name = FONT
    st.element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
doc.styles["Normal"].font.size = Pt(10.5)
for name, size in (("Title", 20), ("Heading 1", 14), ("Heading 2", 12)):
    doc.styles[name].font.size = Pt(size)
    doc.styles[name].font.color.rgb = RGBColor(0x1F, 0x3B, 0x2E)


def p(text, bold=False, size=None):
    para = doc.add_paragraph()
    run = para.add_run(text)
    run.bold = bold
    if size:
        run.font.size = Pt(size)
    return para


def bullets(items):
    for item in items:
        doc.add_paragraph(item, style="List Bullet")


def table(rows, widths=None, header=True, height=None):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    if widths:
        # LibreOffice는 표 격자(gridCol) 너비를 따른다.
        for j, w in enumerate(widths):
            t.columns[j].width = Cm(w)
    for i, row in enumerate(rows):
        for j, text in enumerate(row):
            cell = t.cell(i, j)
            cell.text = text
            if header and i == 0:
                for r in cell.paragraphs[0].runs:
                    r.bold = True
            if widths:
                cell.width = Cm(widths[j])
        if height and i:
            t.rows[i].height = Cm(height)
    doc.add_paragraph()
    return t


